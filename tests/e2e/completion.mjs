import assert from 'node:assert/strict';
import path from 'node:path';

export async function exerciseCompletion(browser, fixture, evidence, readNativeViews) {
  const input = await browser.$('#messageInput');
  const panel = await browser.$('[data-tmc-completion]');
  const options = () => browser.$$('[data-tmc-completion-list] [role="option"]');
  const sentBefore = fixture.sentMessages.length;
  const nativeBefore = await readNativeViews();
  await input.setValue('@autocomplete_h');
  await panel.waitForDisplayed();
  await browser.$('[data-tmc-completion-list] [aria-label="@autocomplete_history"]').waitForDisplayed();
  assert.equal(await browser.$('[data-tmc-emote-picker]').isDisplayed(), false, 'Only one emote/completion panel is open');
  assert.equal(await input.getAttribute('aria-expanded'), 'true');
  await browser.keys('Tab');
  assert.equal(await input.getValue(), '@autocomplete_history ');
  await panel.waitForDisplayed({ reverse: true });
  fixture.sendCompletionUsers();
  await browser.$('[data-tmc-message-id="completion-autocomplete_two"]').waitForExist();
  await input.setValue('@autocomplete_');
  await browser.waitUntil(async () => (await options()).length === 3);
  await browser.keys('ArrowDown');
  assert.equal(await browser.$('[data-tmc-completion-list] [aria-selected="true"]').getAttribute('aria-label'), '@autocomplete_one');
  await browser.keys('Enter');
  assert.equal(await input.getValue(), '@autocomplete_one ');
  assert.equal(fixture.sentMessages.length, sentBefore, 'Enter accepts the choice without submitting chat');
  assert.equal(await browser.execute(`const input = document.querySelector('#messageInput'); const event = new KeyboardEvent('keydown', { key: 'Enter', repeat: true, bubbles: true, cancelable: true }); input.dispatchEvent(event); return event.defaultPrevented;`), true, 'Held Enter cannot submit after accepting a suggestion');
  for (const key of ['Tab', 'Enter']) {
    await input.setValue('hi @autocomplete_h, thanks');
    await browser.execute(`const input = document.querySelector('#messageInput'); const caret = 'hi @autocomplete_h'.length; input.setSelectionRange(caret, caret); input.dispatchEvent(new KeyboardEvent('keyup', { key: 'ArrowLeft', bubbles: true }));`);
    await browser.$('[data-tmc-completion-list] [aria-label="@autocomplete_history"]').waitForDisplayed();
    await browser.keys(key);
    assert.equal(await input.getValue(), 'hi @autocomplete_history, thanks');
    await panel.waitForDisplayed({ reverse: true });
    assert.equal(fixture.sentMessages.length, sentBefore, 'Accepting a mention before punctuation closes completion and never sends');
  }
  await input.setValue('@zzzz');
  await panel.waitForDisplayed();
  assert.equal((await options()).length, 0);
  await browser.keys('ArrowUp');
  assert.equal(await input.getValue(), '@zzzz', 'Empty completion does not recall input history');
  await browser.keys('Escape');
  await input.setValue('draft survives history');
  await browser.keys('ArrowUp');
  assert.equal(await input.getValue(), 'Kappa', 'Closed completion preserves existing command history');
  await browser.keys('ArrowDown');
  assert.equal(await input.getValue(), 'draft survives history');
  // Substitute text entry only: ChromeDriver cannot type non-BMP characters.
  // The actual completion still receives the paste input and native Tab below.
  await browser.execute(`const input = document.querySelector('#messageInput'); input.focus(); input.value = '😀 hi :kappa, world'; input.setSelectionRange('😀 hi :kap'.length, '😀 hi :kap'.length); input.dispatchEvent(new InputEvent('input', { bubbles: true, inputType: 'insertFromPaste' }));`);
  await browser.$('[data-tmc-completion-list] [aria-label="Kappa"]').waitForDisplayed();
  await browser.keys('Tab');
  assert.equal(await input.getValue(), '😀 hi Kappa, world');
  await input.setValue(':kap');
  await browser.$('[data-tmc-completion-list] [aria-label="Kappa"]').waitForDisplayed();
  await browser.$('[data-tmc-completion-list] [aria-label="Kappa"]').click();
  assert.equal(await input.getValue(), 'Kappa ');
  assert.equal(await input.isFocused(), true);
  await input.setValue(':Kee');
  await browser.waitUntil(async () => (await browser.$('[data-tmc-completion-status]').getText()).includes('No matching'));
  assert.equal((await options()).length, 0, 'Unknown/locked A channel emotes are not suggested');
  await browser.keys('Enter');
  assert.equal(await input.getValue(), ':Kee');
  assert.equal(fixture.sentMessages.length, sentBefore);
  await browser.keys('Escape');
  await input.setValue(':kap');
  await browser.$('[data-tmc-completion-list] [aria-label="Kappa"]').waitForDisplayed();
  await browser.execute(`document.querySelector('#messageInput').dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true }))`);
  await panel.waitForDisplayed({ reverse: true });
  assert.equal(await browser.execute(`const input = document.querySelector('#messageInput'); const event = new KeyboardEvent('keydown', { key: 'Enter', isComposing: true, bubbles: true, cancelable: true }); input.dispatchEvent(event); return event.defaultPrevented;`), false, 'IME Enter remains available to composition');
  assert.equal(await input.getValue(), ':kap');
  await browser.execute(`document.querySelector('#messageInput').dispatchEvent(new CompositionEvent('compositionend', { bubbles: true }))`);
  await browser.$('[data-tmc-completion-list] [aria-label="Kappa"]').waitForDisplayed();
  await browser.keys('Tab');
  assert.equal(await input.getValue(), 'Kappa ');
  await input.setValue(':kap');
  await browser.$('[data-tmc-completion-list] [aria-label="Kappa"]').waitForDisplayed();
  assert.deepEqual(await readNativeViews(), nativeBefore, 'Completion leaves native PCG bounds unchanged');
  await browser.saveScreenshot(path.join(evidence, 'chat-completion.png'));
  await browser.$('[data-tmc-emote-open]').click();
  await panel.waitForDisplayed({ reverse: true });
  await browser.$('[data-tmc-emote-picker]').waitForDisplayed();
  await browser.$('[data-tmc-emote-close]').click();
  await browser.$('#channelInput').setValue('fixture-other');
  await browser.$('#openChannelButton').click();
  await browser.$('#openChannelButton').waitForEnabled();
  await input.setValue('@autocomplete_o');
  await panel.waitForDisplayed();
  assert.equal((await options()).length, 0, 'Users from the previous channel are discarded');
  await browser.keys('Escape');
  const blockedBefore = fixture.catalogBlockedRequests.length;
  fixture.holdEmoteCatalog();
  await input.setValue(':kap');
  await browser.waitUntil(async () => fixture.catalogBlockedRequests.length > blockedBefore);
  await browser.$('[data-tmc-account-select]').selectByAttribute('value', 'B');
  await panel.waitForDisplayed({ reverse: true });
  await browser.waitUntil(async () => (await browser.$('[data-tmc-account-status]').getText()).includes('fixture-b'));
  await browser.$('#openChannelButton').waitForEnabled();
  fixture.releaseEmoteCatalog();
  await input.setValue(':BW');
  await browser.$('[data-tmc-completion-list] [aria-label="BWave"]').waitForDisplayed();
  await browser.keys('Tab');
  assert.equal(await input.getValue(), 'BWave ');
  assert.equal(fixture.sentMessages.length, sentBefore, 'Account/channel switches and selections never send/replay');
  await browser.$('[data-tmc-account-select]').selectByAttribute('value', 'A');
  await browser.waitUntil(async () => (await browser.$('[data-tmc-account-status]').getText()).includes('fixture-a'));
  await browser.$('#openChannelButton').waitForEnabled();
  await browser.$('#channelInput').setValue('fixture-channel');
  await browser.$('#openChannelButton').click();
  await browser.$('#openChannelButton').waitForEnabled();
}
