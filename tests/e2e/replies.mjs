import assert from 'node:assert/strict';
import path from 'node:path';

const parentId = '885196de-cb67-427a-baa8-82f9b0fcd05f';

export async function exerciseReplies(browser, fixture, evidence) {
  const sentBefore = fixture.sentMessages.length;
  const preview = await browser.$('[data-tmc-reply-preview]');
  const input = await browser.$('#messageInput');
  fixture.sendReplyMessages();
  const parent = await browser.$(`[data-tmc-message-id="${parentId}"]`);
  const button = await parent.$('.tmc-message-reply-button');
  await parent.waitForDisplayed();
  await browser.$('#chatChannelLabel').moveTo();
  assert.equal(await browser.execute(`return getComputedStyle(document.querySelector('[data-tmc-message-id="${parentId}"] button')).opacity`), '0', 'Reply stays hidden outside the message');
  await parent.moveTo();
  assert.equal(await browser.execute(`return getComputedStyle(document.querySelector('[data-tmc-message-id="${parentId}"] button')).opacity`), '1', 'Hover reveals Reply');
  await browser.$('#chatChannelLabel').moveTo();
  await browser.execute(`document.querySelector('[data-tmc-message-id="${parentId}"] button').focus()`);
  assert.equal(await browser.execute(`return getComputedStyle(document.querySelector('[data-tmc-message-id="${parentId}"] button')).opacity`), '1', 'Keyboard focus also reveals Reply');
  await browser.$('.tmc-message-reply-context').waitForDisplayed();
  assert.match(await browser.$('.tmc-message-reply-context').getText(), /FixtureViewer: hello <img>/);
  await browser.keys('Enter');
  await preview.waitForDisplayed();
  assert.equal(await input.isFocused(), true);
  assert.match(await preview.getText(), /Replying to FixtureViewer: original message/);
  await input.setValue('@oth');
  await browser.$('[data-tmc-completion-list] [aria-label="@other"]').waitForDisplayed();
  await browser.keys('Escape');
  await browser.$('[data-tmc-completion]').waitForDisplayed({ reverse: true });
  assert.equal(await preview.isDisplayed(), true, 'Escape closes suggestions before canceling a reply');
  await input.setValue('draft survives cancel');
  await browser.$('[data-tmc-reply-cancel]').click();
  await preview.waitForDisplayed({ reverse: true });
  assert.equal(await input.getValue(), 'draft survives cancel');
  await parent.moveTo();
  await button.click();
  await browser.keys('Escape');
  await preview.waitForDisplayed({ reverse: true });
  await parent.moveTo();
  await button.click();
  await input.setValue('synthetic-reply');
  await browser.saveScreenshot(path.join(evidence, 'chat-reply.png'));
  await browser.$('#composerForm button[type="submit"]').click();
  await browser.waitUntil(async () => fixture.sentMessages.length === sentBefore + 1);
  await preview.waitForDisplayed({ reverse: true });
  assert.equal(await input.getValue(), '');
  assert.equal(fixture.sentMessages.at(-1).parentMessageId, parentId);
  await browser.$('.tmc-message-self .tmc-message-reply-context').waitForDisplayed();
  await parent.moveTo();
  await button.click();
  await browser.$('[data-tmc-account-select]').selectByAttribute('value', 'B');
  await preview.waitForDisplayed({ reverse: true });
  await browser.waitUntil(async () => (await browser.$('[data-tmc-account-status]').getText()).includes('fixture-b'));
  await browser.$('#openChannelButton').waitForEnabled();
  await browser.waitUntil(async () => (await browser.$('[data-tmc-live-status]').getText()) === 'Live: connected');
  fixture.sendReplyMessages();
  await browser.$(`[data-tmc-message-id="${parentId}"]`).moveTo();
  await browser.$(`[data-tmc-message-id="${parentId}"] .tmc-message-reply-button`).click();
  await preview.waitForDisplayed();
  await browser.$('#channelInput').setValue('fixture-other');
  await browser.$('#openChannelButton').click();
  await preview.waitForDisplayed({ reverse: true });
  await browser.$('#openChannelButton').waitForEnabled();
  await browser.$('#channelInput').setValue('fixture-channel');
  await browser.$('#openChannelButton').click();
  await browser.$('#openChannelButton').waitForEnabled();
  assert.equal(fixture.sentMessages.length, sentBefore + 1, 'Changing context must never replay a reply');
}
